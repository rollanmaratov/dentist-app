-- Support chat: one conversation per patient with the clinic's support desk.
--
-- Patients read their messages through RLS and write only through
-- `send_chat_message` / `mark_chat_read`. Support replies come from the clinic side
-- (`support_reply`, `support_mark_delivered`), which only the service role / SQL editor
-- can call. Images live in the private `chat` bucket under `<patient id>/…`.

-- ---------------------------------------------------------------------------
-- Support agents (the people answering the chat)
-- ---------------------------------------------------------------------------

create table public.support_agents (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (char_length(name) between 1 and 60),
  -- Path in the public `media` bucket.
  avatar_path text,
  created_at timestamptz not null default now()
);

alter table public.support_agents enable row level security;

create policy "Signed-in patients can see support agents"
  on public.support_agents for select to authenticated
  using (true);

insert into public.support_agents (id, name, avatar_path) values
  ('b2f0c3e2-0000-4000-8000-000000000001', 'Jessica', 'support-avatar.png'),
  ('b2f0c3e2-0000-4000-8000-000000000002', 'Katie', 'support-avatar.png');

-- ---------------------------------------------------------------------------
-- Messages
-- ---------------------------------------------------------------------------

create type public.chat_sender as enum ('patient', 'support');

create table public.chat_messages (
  -- Generated by the app so a retried send can't create a duplicate.
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles (id) on delete cascade,
  sender public.chat_sender not null,
  agent_id uuid references public.support_agents (id) on delete set null,
  body text check (char_length(body) between 1 and 4000),
  -- Object paths in the private `chat` bucket.
  image_paths text[] not null default '{}' check (cardinality(image_paths) <= 10),
  created_at timestamptz not null default now(),
  -- Status of the message for its sender: sent (row exists) → delivered → read.
  delivered_at timestamptz,
  read_at timestamptz,
  constraint chat_messages_not_empty check (body is not null or cardinality(image_paths) > 0),
  constraint chat_messages_patient_has_no_agent check (sender = 'support' or agent_id is null)
);

create index chat_messages_patient_created_idx on public.chat_messages (patient_id, created_at desc);
create index chat_messages_unread_idx on public.chat_messages (patient_id) where sender = 'support' and read_at is null;

alter table public.chat_messages enable row level security;

create policy "Patients read their own conversation"
  on public.chat_messages for select to authenticated
  using ((select auth.uid()) = patient_id);

-- Live updates (new messages, delivered/read receipts). Realtime applies the RLS policy above.
alter publication supabase_realtime add table public.chat_messages;

