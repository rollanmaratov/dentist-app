-- Errors: not_authenticated, message_empty, message_too_long, invalid_attachment.
create function public.send_chat_message(p_id uuid, p_body text, p_image_paths text[] default '{}')
returns public.chat_messages
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_body text := nullif(trim(p_body), '');
  v_paths text[] := coalesce(p_image_paths, '{}');
  v_row public.chat_messages;
begin
  if v_uid is null then
    raise exception 'not_authenticated';
  end if;
  if v_body is null and cardinality(v_paths) = 0 then
    raise exception 'message_empty';
  end if;
  if char_length(v_body) > 4000 then
    raise exception 'message_too_long';
  end if;
  -- Only the patient's own uploads: "<uid>/<file name>", at most 10.
  if cardinality(v_paths) > 10 or exists (
    select 1 from unnest(v_paths) p
    where p !~ ('^' || v_uid::text || '/[A-Za-z0-9_-][A-Za-z0-9._-]*$')
  ) then
    raise exception 'invalid_attachment';
  end if;

  insert into public.chat_messages (id, patient_id, sender, body, image_paths)
  values (p_id, v_uid, 'patient', v_body, v_paths)
  on conflict (id) do nothing;

  -- A retry returns the original row; someone else's id is treated as a bad request.
  select * into v_row from public.chat_messages where id = p_id and patient_id = v_uid;
  if not found then
    raise exception 'invalid_message_id';
  end if;
  return v_row;
end;
$$;

-- Marks support messages as read (drives the unread badge). Returns how many changed.
create function public.mark_chat_read()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  update public.chat_messages
  set read_at = now(), delivered_at = coalesce(delivered_at, now())
  where patient_id = auth.uid() and sender = 'support' and read_at is null;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.send_chat_message(uuid, text, text[]) from public, anon;
revoke all on function public.mark_chat_read() from public, anon;

-- ---------------------------------------------------------------------------
-- Support desk functions (SQL editor / service role only)
-- ---------------------------------------------------------------------------

create function public.find_patient_by_phone(p_phone text)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select id from public.profiles
  where regexp_replace(phone, '\D', '', 'g') = regexp_replace(p_phone, '\D', '', 'g');
$$;

-- The desk has opened the conversation: the patient's messages show "Delivered".
create function public.support_mark_delivered(p_phone text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_patient uuid := public.find_patient_by_phone(p_phone);
  v_count integer;
begin
  if v_patient is null then
    raise exception 'patient_not_found';
  end if;
  update public.chat_messages
  set delivered_at = now()
  where patient_id = v_patient and sender = 'patient' and delivered_at is null;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- Reply as an agent, e.g. `select support_reply('77021234567', 'Just do not eat 2 hours before.');`
-- Replying means the desk has read everything before it. Image paths must already be
-- uploaded to the `chat` bucket under the patient's folder.
create function public.support_reply(
  p_phone text,
  p_body text,
  p_agent text default 'Jessica',
  p_image_paths text[] default '{}'
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_patient uuid := public.find_patient_by_phone(p_phone);
  v_agent uuid;
  v_id uuid;
begin
  if v_patient is null then
    raise exception 'patient_not_found';
  end if;
  select id into v_agent from public.support_agents where name = p_agent;
  if v_agent is null then
    raise exception 'agent_not_found';
  end if;
  if exists (select 1 from unnest(coalesce(p_image_paths, '{}')) p where p not like v_patient::text || '/%') then
    raise exception 'invalid_attachment';
  end if;

  update public.chat_messages
  set delivered_at = coalesce(delivered_at, now()), read_at = now()
  where patient_id = v_patient and sender = 'patient' and read_at is null;

  insert into public.chat_messages (patient_id, sender, agent_id, body, image_paths)
  values (v_patient, 'support', v_agent, nullif(trim(p_body), ''), coalesce(p_image_paths, '{}'))
  returning id into v_id;
  return v_id;
end;
$$;

revoke all on function public.find_patient_by_phone(text) from public, anon, authenticated;
revoke all on function public.support_mark_delivered(text) from public, anon, authenticated;
revoke all on function public.support_reply(text, text, text, text[]) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Welcome message for every new patient (and existing ones)
-- ---------------------------------------------------------------------------

create function public.send_chat_welcome()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.chat_messages (patient_id, sender, agent_id, body)
  values (
    new.id,
    'support',
    'b2f0c3e2-0000-4000-8000-000000000001',
    'Hello! This is Doctor Dent support. Ask us anything about your visit — we usually reply within an hour.'
  );
  return new;
end;
$$;

revoke all on function public.send_chat_welcome() from public, anon, authenticated;

create trigger on_profile_created_send_chat_welcome
  after insert on public.profiles
  for each row execute function public.send_chat_welcome();

insert into public.chat_messages (patient_id, sender, agent_id, body)
select
  p.id,
  'support',
  'b2f0c3e2-0000-4000-8000-000000000001',
  'Hello! This is Doctor Dent support. Ask us anything about your visit — we usually reply within an hour.'
from public.profiles p
where not exists (select 1 from public.chat_messages m where m.patient_id = p.id);
